#!/usr/bin/env python3
"""Checked-in manifest of every content-class annotation (docs/content-classes.md).

``docs/content-class-manifest.json`` maps ``<schema file>#<JSON pointer>`` to the class that
location carries (map-key classes carry a ``[keys]`` suffix).  It is generated from the live
annotations by this script and must equal them, so a class can only change in a diff that
shows the change.

``docs/content-class-dispositions.json`` holds the ``legacy_register`` (every location that
was ever ``legacy_content``; it only shrinks through a disposition) and the dispositions
that explain each location that left the register for a content-free class.

Usage::

    python3 scripts/content_class_manifest.py --check
    python3 scripts/content_class_manifest.py --update   # rewrite the manifest only
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "docs" / "content-class-manifest.json"
DISPOSITIONS = ROOT / "docs" / "content-class-dispositions.json"

_spec = importlib.util.spec_from_file_location(
    "content_class_lint", Path(__file__).resolve().parent / "content_class_lint.py"
)
assert _spec and _spec.loader
lint = importlib.util.module_from_spec(_spec)
sys.modules.setdefault("content_class_lint", lint)
_spec.loader.exec_module(lint)

COMMENT = (
    "Generated by scripts/content_class_manifest.py --update; do not hand-edit. Maps every "
    "annotated location (schema file#JSON pointer; '[keys]' = map-key class) to its "
    "x-content-class. A class change shows up here, and a location leaving legacy_content "
    "needs an entry in docs/content-class-dispositions.json."
)


def live_classes() -> dict[str, str]:
    result = lint.run_lint()
    return {f.loc: f.cls for f in result.findings if f.cls}


def render(classes: dict[str, str]) -> str:
    body = {"_comment": COMMENT, "classes": dict(sorted(classes.items()))}
    return json.dumps(body, indent=1, sort_keys=False, ensure_ascii=False) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--check", action="store_true")
    g.add_argument("--update", action="store_true")
    args = ap.parse_args(argv)
    text = render(live_classes())
    if args.update:
        MANIFEST.write_text(text, encoding="utf-8")
        print(f"wrote {MANIFEST}")
        return 0
    if not MANIFEST.exists() or MANIFEST.read_text(encoding="utf-8") != text:
        print(f"{MANIFEST} is stale; run with --update", file=sys.stderr)
        return 1
    print("content-class manifest up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
